package com.polaris.nucleo.domain.model;

/** Lo que mide un logro de Nucleo: el peso, las medidas y el perfil. */
public enum MetricaLogro {
    /** Dias con peso apuntado. */
    PESAJES,
    /** La racha mas larga de dias seguidos con peso apuntado. */
    RACHA_PESAJES,
    /** Dias con medidas apuntadas. */
    MEDIDAS,
    /** Campos del perfil rellenos: altura, nacimiento, sexo y actividad. */
    PERFIL
}
